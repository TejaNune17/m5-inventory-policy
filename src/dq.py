"""Run data quality checks (sql/01_data_quality.sql) and write docs/dq_report.md.

Fails loudly if source-to-target reconciliation does not match exactly.
"""
from __future__ import annotations

from common import ROOT, connect, load_config, run_sql_file


def fmt(check: str, v: float) -> str:
    if v is None:
        return "null"
    if "share" in check:
        return f"{v:.2%}"
    if float(v).is_integer():
        return f"{int(v):,}"
    return f"{v:,.4f}"


def reconcile(res: dict[str, float]) -> list[tuple[str, float, float, bool]]:
    pairs = [
        ("sales series", "sales: source series rows", "sales: loaded distinct series"),
        ("sales long rows", "sales: expected long rows (series x d columns)", "sales: loaded fact_sales rows"),
        ("calendar rows", "calendar: source rows", "calendar: loaded rows"),
        ("price rows", "prices: source rows", "prices: loaded rows"),
    ]
    return [(name, res[a], res[b], res[a] == res[b]) for name, a, b in pairs]


def main() -> None:
    cfg = load_config()
    con = connect(cfg)
    run_sql_file(con, ROOT / "sql" / "01_data_quality.sql", cfg["dq"])
    df = con.execute("SELECT * FROM dq_results").df()
    span = con.execute("SELECT min(date), max(date), count(*) FROM fact_sales GROUP BY item_id, store_id LIMIT 1").fetchone()
    con.close()

    res = dict(zip(df["check_name"], df["value"]))
    recon = reconcile(res)

    lines = [
        "# Data quality report",
        "",
        "Generated by `src/dq.py` from `sql/01_data_quality.sql`. Do not edit by hand.",
        "",
        f"Sales date range: {span[0]} to {span[1]} ({span[2]:,} days per series).",
        "",
        "## Source-to-target reconciliation",
        "",
        "| Item | Source | Loaded | Match |",
        "|---|---:|---:|---|",
    ]
    lines += [f"| {n} | {int(a):,} | {int(b):,} | {'yes' if ok else 'NO'} |" for n, a, b, ok in recon]
    lines += ["", "## Checks", "", "| Section | Check | Result | Treatment |", "|---|---|---:|---|"]
    lines += [
        f"| {r.section} | {r.check_name} | {fmt(r.check_name, r.value)} | {r.treatment} |"
        for r in df.itertuples()
    ]
    lines += [
        "",
        "## Treatment rules",
        "",
        "- Leading zeros before a series' first sale are pre-launch and excluded (`v_sales_clean`).",
        "- Mid-series and trailing zeros are kept as zero demand. Sales-only data cannot distinguish a stockout "
        "from no demand; long runs are flagged above, not removed.",
        "- Price outliers are kept. They are real shelf prices (promotions, corrections) and are used as features.",
        "",
    ]
    out = ROOT / "docs" / "dq_report.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")

    failed = [n for n, _, _, ok in recon if not ok]
    if failed:
        raise SystemExit(f"reconciliation failed: {failed}")
    print("reconciliation passed")


if __name__ == "__main__":
    main()
